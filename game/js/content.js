/** 把秒數寫成好讀的中文：85 →「85 秒」、120 →「2 分鐘」、170 →「2 分 50 秒」 */
export function formatDuration(sec) {
  const s = Math.max(0, Math.round(Number(sec) || 0));
  if (s < 90) return `${s} 秒`;
  const m = Math.floor(s / 60), r = s % 60;
  return r ? `${m} 分 ${r} 秒` : `${m} 分鐘`;
}
